// Full OCR boxes and cells stay in the bundle; the model receives short exact
// excerpts so multi-page scans do not exhaust its bounded context.
func modelDatasetActions(actions []models.DatasetResult) []models.DatasetResult {
	result := append([]models.DatasetResult{}, actions...)
	for i := range result {
		result[i].OCRPages = nil
		result[i].Passages = append([]models.EvidencePassage{}, result[i].Passages...)
		for j := range result[i].Passages {
			if len(result[i].Passages[j].Text) > 2000 {
				result[i].Passages[j].Text = string([]rune(result[i].Passages[j].Text)[:min(1000, len([]rune(result[i].Passages[j].Text)))]) + " [excerpt truncated; full page in evidence]"
			}
		}
		result[i].Tables = append([]models.ExtractedTable{}, result[i].Tables...)
		for j := range result[i].Tables {
			result[i].Tables[j].CellSources = nil
			if len(result[i].Tables[j].Rows) > 6 {
				result[i].Tables[j].Rows = result[i].Tables[j].Rows[:6]
			}
		}
	}
	return result
}

// Expose exact server-issued table references as callable arguments; the model
// must not reconstruct hashes or confuse a scan result with a table extraction.
func availableTableSaves(actions []models.DatasetResult) []models.DatasetCall {
	calls := []models.DatasetCall{}
	for _, a := range actions {
		if a.Error != "" {
			continue
		}
		for _, table := range a.Tables {
			calls = append(calls, models.DatasetCall{Tool: "paper-table", URL: a.Call.URL, Page: table.Page, TableIndex: table.Index, ExtractionID: a.ExtractionID})
		}
	}
	return calls
}

// Failed attempts cannot expose a successful statistic to guide subsequent filtering.
func hasSuccessfulCalculation(results []models.VerificationResult) bool {
	for _, r := range results {
		if r.Status == "completed" {
			return true
		}
	}
	return false
}

// Only a successful retry of the same calculation resolves its earlier failure.
func calculationRecovered(failed models.VerificationResult, later []models.VerificationResult) bool {
	for _, r := range later {
		if r.Status == "completed" && r.Call.Tool == failed.Call.Tool && r.Call.GroupColumn == failed.Call.GroupColumn && r.Call.ValueColumn == failed.Call.ValueColumn {
			return true
		}
	}
	return false
}
